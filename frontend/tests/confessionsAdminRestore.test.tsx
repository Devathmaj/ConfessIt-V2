import { render, screen, within, fireEvent, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { beforeEach, describe, expect, it, vi } from 'vitest';

import { AuthContext } from '@/contexts/AuthContext';
import { ConfessionsAdmin } from '@/pages/ConfessionsAdmin';

const api = vi.hoisted(() => ({
  getAdminConfessions: vi.fn(),
  hideAdminConfession: vi.fn(),
  hideAdminComment: vi.fn(),
  unhideAdminConfession: vi.fn(),
  unhideAdminComment: vi.fn(),
}));

vi.mock('@/services/api', () => api);
vi.mock('sonner', () => ({
  toast: { info: vi.fn(), error: vi.fn(), success: vi.fn() },
  Toaster: () => null,
}));

const NOW = '2026-01-15T10:00:00Z';
const HIDDEN_AT = '2026-01-16T12:30:00Z';

const azureConfession = {
  id: '22222222-2222-2222-2222-222222222222',
  body: 'azure hidden post',
  recipient_name: null,
  anonymous: false,
  sender_hidden: false,
  comments_enabled: true,
  created_at: NOW,
  sender: { id: 'author-1', name: 'The Author', regno: 'author', email: 'author@test.com' },
  report_count: 1,
  reported_by: [],
  reports: [{ id: 'r1', reason: 'Automatically generated by Azure AI Content Safety.', created_at: NOW, reporter: { id: null, name: 'Azure Content Safety' } }],
  reactions: {},
  heart_count: 0,
  haha_count: 0,
  whoa_count: 0,
  heartbreak_count: 0,
  comment_count: 0,
  comments: [],
  content_removed: true,
  removed_at: HIDDEN_AT,
  removed_by_regno: 'azure-content-safety',
};

const manualConfession = {
  ...azureConfession,
  id: '33333333-3333-3333-3333-333333333333',
  body: 'moderator hidden post',
  removed_by_regno: 'moduser',
};

function renderPage() {
  return render(
    <AuthContext.Provider
      value={
        {
          user: { id: 'admin-1', regno: 'ADMIN-1', name: 'Admin', account_type: 'admin', capabilities: [], is_blocked: false },
          isAuthenticated: true,
          loading: false,
          can: () => true,
        } as never
      }
    >
      <MemoryRouter>
        <ConfessionsAdmin />
      </MemoryRouter>
    </AuthContext.Provider>,
  );
}

async function expandFirstRow() {
  const trigger = await screen.findByRole('button', { expanded: false });
  fireEvent.click(trigger);
  await screen.findByRole('button', { expanded: true });
}

describe('ConfessionsAdmin: restore Azure-hidden content', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    vi.mocked(api.getAdminConfessions).mockResolvedValue([azureConfession]);
  });

  it('labels Azure removals and offers restore', async () => {
    renderPage();
    await screen.findByText('azure hidden post');
    await expandFirstRow();
    expect(screen.getByText(/Content Removed by Azure Content Safety/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: /restore confession/i })).toBeInTheDocument();
  });

  it('warns users will now be able to see this before restoring', async () => {
    vi.mocked(api.unhideAdminConfession).mockResolvedValue({ id: azureConfession.id, content_removed: false });
    renderPage();
    await screen.findByText('azure hidden post');
    await expandFirstRow();
    fireEvent.click(screen.getByRole('button', { name: /restore confession/i }));
    const dialog = await screen.findByRole('alertdialog');
    expect(within(dialog).getByText(/users will now be able to see this/i)).toBeInTheDocument();
    fireEvent.click(within(dialog).getByRole('button', { name: /^restore confession$/i }));
    await waitFor(() => {
      expect(api.unhideAdminConfession).toHaveBeenCalledWith(azureConfession.id);
    });
  });

  it('does not offer restore for moderator hides', async () => {
    vi.mocked(api.getAdminConfessions).mockResolvedValue([manualConfession]);
    renderPage();
    await screen.findByText('moderator hidden post');
    await expandFirstRow();
    expect(screen.getByText(/cannot be restored here/i)).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: /restore confession/i })).not.toBeInTheDocument();
  });
});
