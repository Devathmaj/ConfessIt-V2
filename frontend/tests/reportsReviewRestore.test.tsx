import { render, screen, within, fireEvent, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { beforeEach, describe, expect, it, vi } from 'vitest';

import { AuthContext } from '@/contexts/AuthContext';
import { ReportsReview } from '@/pages/ReportsReview';

const api = vi.hoisted(() => ({
  getAdminConfessionReports: vi.fn(),
  getAdminLoveNoteReports: vi.fn(),
  getAdminMessageReports: vi.fn(),
  updateAdminConfessionReportStatus: vi.fn(),
  updateAdminLoveNoteReportStatus: vi.fn(),
  updateAdminMessageReportStatus: vi.fn(),
  unhideAdminConfession: vi.fn(),
  unhideAdminComment: vi.fn(),
}));

vi.mock('@/services/api', () => api);
vi.mock('sonner', () => ({
  toast: { info: vi.fn(), error: vi.fn(), success: vi.fn() },
  Toaster: () => null,
}));

const NOW = '2026-01-15T10:00:00Z';

const azureReport = {
  id: '11111111-1111-1111-1111-111111111111',
  target_type: 'confession',
  target_id: '22222222-2222-2222-2222-222222222222',
  confession_id: '22222222-2222-2222-2222-222222222222',
  parent_recipient_name: null,
  parent_confession: null,
  anonymous: false,
  content: 'azure hidden body',
  content_created_at: NOW,
  author: { id: 'a1', name: 'Author', regno: 'author' },
  author_hidden: false,
  reporter: { id: null, name: 'Azure Content Safety' },
  reason: 'Automatically generated by Azure AI Content Safety.',
  reported_at: NOW,
  status: 'removed',
  reviewed_at: NOW,
  reviewed_by_regno: 'azure-content-safety',
  content_removed: true,
  removed_at: NOW,
  removed_by_regno: 'azure-content-safety',
};

const emptyQueue = { reports: [], total: 0, skip: 0, limit: 50 };

function renderPage() {
  return render(
    <AuthContext.Provider
      value={
        {
          user: { id: 'admin-1', regno: 'ADMIN-1', name: 'Admin', account_type: 'admin', capabilities: [], is_blocked: false },
          isAuthenticated: true,
          loading: false,
          can: () => true,
        } as never
      }
    >
      <MemoryRouter>
        <ReportsReview />
      </MemoryRouter>
    </AuthContext.Provider>,
  );
}

async function expandCard() {
  const header = await screen.findByRole('button', { name: /Confession reported by Azure Content Safety/i });
  fireEvent.click(header);
  await screen.findByRole('button', { name: /restore content/i });
}

describe('ReportsReview: restore Azure-hidden content', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    vi.mocked(api.getAdminConfessionReports).mockResolvedValue({ reports: [azureReport], total: 1, skip: 0, limit: 50 });
    vi.mocked(api.getAdminLoveNoteReports).mockResolvedValue(emptyQueue);
    vi.mocked(api.getAdminMessageReports).mockResolvedValue(emptyQueue);
  });

  it('labels Azure removals and offers restore', async () => {
    renderPage();
    await screen.findByText(/Content removed by Azure Content Safety/);
    await expandCard();
    expect(screen.getByRole('button', { name: /restore content/i })).toBeInTheDocument();
  });

  it('warns users will now be able to see this before restoring', async () => {
    vi.mocked(api.unhideAdminConfession).mockResolvedValue({ id: azureReport.target_id, content_removed: false });
    renderPage();
    await screen.findByText(/Content removed by Azure Content Safety/);
    await expandCard();
    fireEvent.click(screen.getByRole('button', { name: /restore content/i }));
    const dialog = await screen.findByRole('alertdialog');
    expect(within(dialog).getByText(/users will now be able to see this/i)).toBeInTheDocument();
    fireEvent.click(within(dialog).getByRole('button', { name: /restore content/i }));
    await waitFor(() => {
      expect(api.unhideAdminConfession).toHaveBeenCalledWith(azureReport.target_id);
    });
  });
});
