"""Configuring the day's Wordle puzzle: which word the day runs on, and where it came from.

The table this writes is the *configuration* of a puzzle and nothing else -- a day, a word,
and whether the word was typed or drawn. There is no attempt, no guess and no result here,
because there is no gameplay yet, and the separation is worth stating rather than assuming:
every write below is an administrator publishing something, and none of it is ever triggered
by a participant.

**The word list is data, not a dependency.** ``backend/app/data/wordle_solutions.json`` is
committed and read from disk, so the running application needs no npm package and no network.
The list is regenerated only when the vocabulary itself changes, by
``scripts/generate-wordle-words.mjs``; nothing at runtime reaches for anything but the file.
The file is validated on first read rather than trusted: a committed artifact is exactly the
kind of thing that gets edited by hand one day, and a short word silently joining the list
would be accepted by this service and then rejected by the column it is written to.

The *guess* vocabulary is the same story one file over. ``wordle_guesses.json`` is the union
of the package's two lists (solutions plus valid-but-never-winning words), regenerated by
``scripts/generate-wordle-guesses.mjs``, and it is the set a submitted guess is tested
against. It lives here rather than in the gameplay service because it is data, and this
module owns the word data.

**A drawn word is bound to the day it was drawn for.** ``GET /admin/wordle/preview`` picks a
word and signs it together with the date; ``POST /admin/wordle`` re-derives the signature
before storing. That is what makes the preview honest -- the admin sees the answer *before*
saving, and saving cannot produce a different one -- while keeping the choice on the server:
the client echoes a word back only alongside a signature it cannot forge, so no client can
supply an answer of its own making under ``mode="random"``.
"""

import hashlib
import hmac
import json
import random
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from fastapi import HTTPException, status
from sqlalchemy import func, select
from sqlalchemy.exc import IntegrityError

from ..config import settings
from ..db_models import WordleGameRecord
from ..limits import WORDLE_ANSWER_LENGTH
from ..models import WordleDraw, WordleGame, WordleGameCreate
from ..postgres import Database, is_valid_id

# Next to this package rather than inside it: ``app.data`` would be an importable package only
# with an ``__init__.py`` it does not need, and the file is data rather than code.
_SOLUTIONS_PATH = Path(__file__).resolve().parent.parent / "data" / "wordle_solutions.json"
_GUESSES_PATH = Path(__file__).resolve().parent.parent / "data" / "wordle_guesses.json"

# Loaded once and reused for the process's life. The list is read on the first draw or the
# first custom word, not at import: a module that fails to import would take the application
# down before it could log why, where a failure here is a request that answers 500 with the
# reason attached.
_solutions: Optional[tuple[str, ...]] = None
_guesses: Optional[tuple[str, ...]] = None


def solution_words() -> tuple[str, ...]:
    """Every approved solution word, loaded once and validated on the way in."""
    global _solutions
    if _solutions is None:
        words = json.loads(_SOLUTIONS_PATH.read_text(encoding="utf-8"))
        malformed = [word for word in words if not _is_well_formed(word)]
        if malformed:
            raise RuntimeError(
                f"{_SOLUTIONS_PATH} holds {len(malformed)} entries that are not exactly "
                f"{WORDLE_ANSWER_LENGTH} lowercase letters, first: {malformed[0]!r}"
            )
        _solutions = tuple(words)
    return _solutions


def _is_well_formed(word: object) -> bool:
    return isinstance(word, str) and len(word) == WORDLE_ANSWER_LENGTH and word.islower() and word.isalpha()


def guess_words() -> tuple[str, ...]:
    """Every word a player is allowed to type, loaded once and validated on the way in.

    The playing surface of Wordle has two vocabularies: words that can be an *answer* and
    words that can only ever be a *guess*. The answer list is committed separately above;
    this is the union of the two, which is the text the guess-acceptance check tests against
    -- a five-letter word that could never win the day is still a legal guess, and a typed
    word that is not in this set is refused as not a word at all.
    """
    global _guesses
    if _guesses is None:
        words = json.loads(_GUESSES_PATH.read_text(encoding="utf-8"))
        malformed = [word for word in words if not _is_well_formed(word)]
        if malformed:
            raise RuntimeError(
                f"{_GUESSES_PATH} holds {len(malformed)} entries that are not exactly "
                f"{WORDLE_ANSWER_LENGTH} lowercase letters, first: {malformed[0]!r}"
            )
        _guesses = tuple(words)
    return _guesses


def _today() -> date:
    return datetime.now(timezone.utc).date()


# --- the draw ------------------------------------------------------------------


def _signature(word: str, game_date: date) -> str:
    message = f"{word}|{game_date.isoformat()}".encode("utf-8")
    return hmac.new(settings.SECRET_KEY.encode("utf-8"), message, hashlib.sha256).hexdigest()


def draw_answer(game_date: Optional[date] = None) -> WordleDraw:
    """Pick a word from the approved list for ``game_date`` and sign the pair.

    The date is part of the signature rather than a comment on it: a draw made for Monday
    cannot be submitted as Tuesday's puzzle, so an admin who draws, changes the date field
    and saves is refused and asked to draw again -- rather than silently publishing a word
    for a day it was never chosen for.
    """
    day = game_date or _today()
    word = random.choice(solution_words())
    return WordleDraw(word=word, token=_signature(word, day))


def _require_approved(word: Optional[str], missing_detail: str) -> str:
    """Normalize a supplied word and refuse anything that is not on the approved list.

    One place for the three rules -- present, five letters, in the list -- so custom and
    random modes cannot drift into answering them differently. The answer to a wrong word is
    a 400 rather than a 422: the request was well-formed, it asked for something this
    server will not do.
    """
    if word is None or not word.strip():
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=missing_detail)
    normalized = word.strip().lower()
    if len(normalized) != WORDLE_ANSWER_LENGTH:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"An answer is exactly {WORDLE_ANSWER_LENGTH} letters.",
        )
    if normalized not in solution_words():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="That word is not on the approved list.",
        )
    return normalized


def _resolve_answer(payload: WordleGameCreate, game_date: date) -> str:
    """The word to store for this payload, for either mode."""
    if payload.mode == "custom":
        return _require_approved(payload.word, "A custom game needs a word.")

    # Random: the word must be one this server signed for this exact day. The membership
    # check runs again even though a signature could only have been minted over a word from
    # the list -- the file can be regenerated between a draw and a save, and the row must
    # never hold a word the current list would refuse.
    answer = _require_approved(payload.word, "Draw a word before saving a random game.")
    signed = _signature(answer, game_date)
    if payload.token is None or not hmac.compare_digest(signed, payload.token):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="That draw does not match this date. Draw a new word and save again.",
        )
    return answer


# --- persistence ---------------------------------------------------------------


def _as_model(row: WordleGameRecord) -> WordleGame:
    return WordleGame(
        id=str(row.id),
        game_date=row.game_date,
        mode=row.mode,
        answer=row.answer,
        status=row.status or "active",
        period_start_date=row.period_start_date,
        period_end_date=row.period_end_date,
        created_at=row.created_at,
        updated_at=row.updated_at,
    )


def _current_session_row(session):
    """The one active-or-pending Wordle session, or None."""
    return session.scalar(
        select(WordleGameRecord)
        .where(WordleGameRecord.status.in_(("active", "pending")))
        .limit(1)
    )


def update_wordle_session(
    db: Database,
    *,
    mode: Optional[str] = None,
    word: Optional[str] = None,
    token: Optional[str] = None,
    updated_by: str = "admin",
    now: Optional[datetime] = None,
    discard_future_schedules: bool = False,
) -> WordleGame:
    """End the current session and open a brand-new one starting now ("Update").

    Never mutates the old row: it is stamped ended and kept as history with its
    user progress attached, while the new session starts from scratch. The new
    session's period runs from today's UTC date under the game's own reset
    cadence -- an update at 23:58 does not buy a fresh 24 hours. When ``mode``
    is given, the game's content mode follows the update: a custom word means
    manual from now on, a drawn word means random; ``mode=None`` keeps the
    stored mode (cadence-change re-anchoring). Atomic under the game's
    advisory lock, so an Update racing the 00:01 reset cannot leave two active
    sessions.

    Content resolution: a supplied word wins (validated as today, exactly like
    before, with random draws still requiring their signed token). Without a
    supplied word in manual mode, the earliest scheduled entry inside the new
    window is consumed, or the session opens pending when the window holds
    none. A random update without a draw is still refused. Other pending
    scheduled entries dated before the window end are discarded; with
    ``discard_future_schedules`` (cadence-change re-anchoring) every other
    pending entry goes too, since the old rhythm no longer exists.
    """
    from sqlalchemy import text as _text

    from . import game_periods
    from .game_configs import game_lock_key, get_config
    from .game_scheduler import (
        _consume_earliest_word,
        _discard_all_scheduled_words,
        _discard_scheduled_words_before,
    )

    moment = now or datetime.now(timezone.utc)
    today = moment.date()
    if word is not None:
        # An Update always applies to the current session: the draw it
        # confirms was previewed for today, so the signature is verified
        # against today.
        resolve_mode = mode if mode is not None else "custom"
        answer: Optional[str] = _resolve_answer(
            WordleGameCreate(mode=resolve_mode, word=word, token=token),  # type: ignore[arg-type]
            today,
        )
        supplied = True
    elif mode == "random":
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Draw a word before saving a random game.",
        )
    else:
        answer = None
        supplied = False

    try:
        with db.sessions.begin() as session:
            session.execute(
                _text("SELECT pg_advisory_xact_lock(:key)"),
                {"key": game_lock_key("wordle")},
            )
            config = get_config(session, "wordle")
            if mode is not None:
                # Session modes (custom/random) are provenance; content modes
                # (manual/random) are behaviour. A typed word means manual
                # from now on, a drawn word means random.
                config.content_mode = "manual" if mode == "custom" else "random"
            effective_mode = config.content_mode or "manual"
            if not supplied and effective_mode == "random":
                raise HTTPException(
                    status_code=status.HTTP_400_BAD_REQUEST,
                    detail="Draw a word before saving a random game.",
                )
            session_mode = "random" if effective_mode == "random" else "custom"
            cadence = config.reset_cadence
            current = _current_session_row(session)
            if current is not None:
                current.status = "ended"
                current.ended_at = moment
            start, end = game_periods.period_for_start(today, cadence)
            if not supplied and effective_mode == "manual":
                answer = _consume_earliest_word(session, "wordle", start, end)
                if discard_future_schedules:
                    _discard_all_scheduled_words(session, "wordle")
                else:
                    _discard_scheduled_words_before(session, "wordle", end)
            elif supplied and effective_mode == "manual":
                if discard_future_schedules:
                    _discard_all_scheduled_words(session, "wordle")
                else:
                    _discard_scheduled_words_before(session, "wordle", end)
            row = WordleGameRecord(
                game_date=today,
                mode=session_mode if mode is None else mode,
                answer=answer,
                status="active" if answer else "pending",
                period_start_date=start,
                period_end_date=end,
                started_at=moment,
            )
            session.add(row)
            session.flush()
            from . import league_finalization

            league_finalization.snapshot_opened_safely(
                session, game_id="wordle", opportunity_id=str(row.id)
            )
            result = _as_model(row)
        # The Update deliberately closes the previous session, so its awards
        # finalize now rather than waiting for the next reset run.
        league_finalization.finalize_game_safely(db, "wordle")
        return result
    except IntegrityError as exc:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="A Wordle session update collided with a concurrent reset. Try again.",
        ) from exc


def create_wordle_game(db: Database, payload: WordleGameCreate) -> WordleGame:
    """Publish the current Wordle session ("Update").

    ``POST /admin/wordle`` is the Update action: it ends the currently
    active/pending session and opens a new one for today. An explicit
    ``game_date`` other than today is refused -- future words belong on the
    schedule endpoint (bounded by ``MAX_FUTURE_SCHEDULE_DAYS``), and history is
    read-only. The preview draw an Update confirms was made for today, so the
    signature is verified against today's date.
    """
    game_date = payload.game_date or _today()
    if game_date != _today():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=(
                "Updates apply to the current session. "
                "Schedule future words with POST /admin/wordle/schedule."
            ),
        )
    return update_wordle_session(
        db, mode=payload.mode, word=payload.word, token=payload.token
    )


# Hard ceiling for one page of the session-history list. The endpoint clamps anything
# larger, so no client can ask for every session at once and make the backend
# materialise a whole season in one response.
WORDLE_GAMES_MAX_LIMIT = 100


def list_wordle_games(
    db: Database, *, skip: int = 0, limit: int = 50
) -> Dict[str, Any]:
    """One page of every session, newest first -- active, pending and ended history alike.

    The page is a SQL LIMIT/OFFSET and ``total`` a COUNT, so the screen loads history
    downwards without ever holding the sessions it is not showing. ``id`` seconds the
    order so two sessions stamped in the same instant still page deterministically.
    """
    skip = max(0, int(skip or 0))
    limit = max(1, min(int(limit or 50), WORDLE_GAMES_MAX_LIMIT))
    with db.sessions() as session:
        total = session.scalar(select(func.count()).select_from(WordleGameRecord)) or 0
        rows = session.scalars(
            select(WordleGameRecord)
            .order_by(WordleGameRecord.created_at.desc(), WordleGameRecord.id.asc())
            .offset(skip).limit(limit)
        ).all()
        games = [_as_model(row) for row in rows]
    return {"games": games, "total": total, "skip": skip, "limit": limit}


def get_current_wordle_session(db: Database) -> Optional[WordleGame]:
    """The current active-or-pending session for the admin screen, if any."""
    with db.sessions() as session:
        row = _current_session_row(session)
        return _as_model(row) if row is not None else None


def get_wordle_game(db: Database, game_id: str) -> WordleGame:
    """One configured puzzle by id.

    A malformed id is a 400 and a well-formed one that matches nothing is a 404, so a typo in
    a URL and a puzzle that has been superseded are told apart rather than both reported as
    "not found".
    """
    if not is_valid_id(game_id):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST, detail="Invalid Wordle game id"
        )
    with db.sessions() as session:
        row = session.get(WordleGameRecord, str(game_id))
    if row is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND, detail="Wordle game not found"
        )
    return _as_model(row)
