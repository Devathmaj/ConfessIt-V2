@router.get("/session")
def current_session(
    db: Database = Depends(get_db),
    _: AccountDetails = Depends(require_capability(Capability.GAMES_MANAGE)),
) -> dict:
    """The current Case Closed session: its published content and generation state.

    ``session`` is the playable event pinned to its published case package -- never a
    blueprint or unpublished draft -- and is ``null`` while generation is in flight or
    when nothing is active. ``generation`` carries the latest cycle's status or last
    error so the console can explain why no session is available yet.
    """
    return ai_game_automation.current_session_overview(db, "case-closed")


@router.get("/sessions")
def list_sessions(
    skip: int = Query(0, ge=0, le=PAGE_OFFSET_MAX),
    limit: int = Query(AI_GENERATION_HISTORY_DEFAULT_LIMIT, ge=1, le=AI_GENERATION_HISTORY_MAX_LIMIT),
    db: Database = Depends(get_db),
    _: AccountDetails = Depends(require_capability(Capability.GAMES_MANAGE)),
) -> dict:
    """One backend page of Case Closed session history, newest first.

    Same envelope convention and hard limit as every other games history read, so a
    long season is never loaded in one response.
    """
    return ai_game_automation.list_sessions(db, "case-closed", skip=skip, limit=limit)


@router.post("/session/revoke")
def revoke_session(
    db: Database = Depends(get_db),
    account: AccountDetails = Depends(require_capability(Capability.GAMES_MANAGE)),
) -> dict:
    """End the live session (or cancel its generation) without replacing it.

    Supersession lasts until the next eligible scheduled cycle; repeated calls with
    nothing live are a safe no-op, and hiding or disabling the game remains a separate
    control with its own semantics.
    """
    return ai_game_automation.revoke_current_session(
        db, "case-closed", account.regno
    )
